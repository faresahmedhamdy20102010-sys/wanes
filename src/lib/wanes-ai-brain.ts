export async function executeLLMCompanionTurn(
  userPrompt: string,
  history: { sender: "bot" | "user"; text: string }[],
  context: ConversationContext,
  config: AIProviderConfig
): Promise<LLMTurnResult> {
  let contextInfo = "DYNAMIC RUNTIME CONTEXT:\n"
  if (context.userName) {
    contextInfo += `- Client Name: ${context.userName}\n`
  }
  if (context.userGender) {
    contextInfo += `- Client Registered Gender: ${context.userGender.toUpperCase()} (Strict Same-Gender rule active)\n`
  }

  if (context.activeDraft && !context.activeDraft.isDeployed) {
    contextInfo += `- ACTIVE PENDING ORDER DRAFT IN MEMORY:\n`
    contextInfo += `  Title: "${context.activeDraft.title}"\n`
    contextInfo += `  Category: ${context.activeDraft.category}\n`
    contextInfo += `  Description: "${context.activeDraft.description}"\n`
    contextInfo += `  Urgency: ${context.activeDraft.urgency}\n`
    contextInfo += `  Recipient: ${context.activeDraft.recipientName || "Elder"}\n`
    contextInfo += `  Location: ${context.activeDraft.locationText || "Cairo"}\n`
    contextInfo += `  Estimated Price: ${context.activeDraft.estimatedPrice} EGP\n`
    contextInfo += `  80% Paymob Escrow: ${context.activeDraft.escrowAmount} EGP\n`
    contextInfo += `  Instruction: If the user says "yes", "deploy it", "confirm", or approves deployment, output action: {"type": "deploy_order"}\n`
  }

  const llmResponse = await queryRealLLM(userPrompt, history, config, contextInfo)

  if (llmResponse.rawText && !llmResponse.error) {
    const parsedOutput = parseLLMJsonOutput(llmResponse.rawText)
    const action = parsedOutput.action

    if (!action || typeof action !== "object") {
      return {
        message: parsedOutput.message,
        intent: null,
      }
    }

    let intent: ParsedIntent | null = null

    switch (action.type) {
      case "create_order": {
        intent = {
          type: "order",
          category: (action.category as RequestCategory) || "senior_care",
          title: action.title || "Companion Visit Request",
          description: action.description || userPrompt,
          urgency: (action.urgency as RequestUrgency) || "normal",
          recipientName: action.recipientName || undefined,
          locationText: action.locationText || "Cairo, Egypt",
          estimatedPrice: typeof action.estimatedPrice === "number" ? action.estimatedPrice : 450,
          escrowAmount:
            typeof action.escrowAmount === "number"
              ? action.escrowAmount
              : Math.round((action.estimatedPrice || 450) * 0.80 * 100) / 100,
        }
        break
      }

      case "deploy_order": {
        intent = {
          type: "confirm_deploy",
          draft: context.activeDraft || undefined,
        }
        break
      }

      case "navigate": {
        const rawTarget = (action.targetRoute || "dashboard").toString().replace(/^\//, "")
        const targetRoute: Route = VALID_ROUTES.includes(rawTarget as Route)
          ? (rawTarget as Route)
          : "dashboard"
        intent = {
          type: "navigate",
          targetRoute,
          pageName: action.pageName || "Platform Navigation",
        }
        break
      }

      case "trigger_urgent_service": {
        intent = {
          type: "urgent_service",
        }
        break
      }

      case "open_booking_flow": {
        intent = {
          type: "open_booking",
          category: (action.category as RequestCategory) || "senior_care",
          title: action.title || "Companion Care Visit",
          description: action.description || userPrompt,
          locationText: action.locationText || "Cairo, Egypt",
          estimatedPrice: typeof action.estimatedPrice === "number" ? action.estimatedPrice : 450,
          escrowAmount: typeof action.escrowAmount === "number" ? action.escrowAmount : 360,
        }
        break
      }

      case "detect_location": {
        intent = {
          type: "location",
          query: userPrompt,
        }
        break
      }

      case "trigger_sos": {
        intent = {
          type: "sos",
          reason: action.reason || userPrompt,
        }
        break
      }

      case "fill_form": {
        intent = {
          type: "form_fill",
          fields: action.fields || { notes: userPrompt },
        }
        break
      }

      case "out_of_scope":
      default: {
        intent = null
        break
      }
    }

    return {
      message: enforceStrictEnglish(parsedOutput.message, userPrompt),
      intent,
    }
  }

  const cognition = executeAutonomousCognition(userPrompt, context)
  return {
    ...cognition,
    message: enforceStrictEnglish(cognition.message, userPrompt),
  }
}
