export function isArabicText(text: string): boolean {
  return /[\u0600-\u06FF]/.test(text)
}

export function enforceStrictEnglish(text: string, originalUserPrompt?: string): string {
  if (!text) return "I am ready to assist you with the Wanes platform."

  const hasArabic = /[\u0600-\u06FF]/.test(text)
  if (!hasArabic) {
    return text.trim()
  }

  const lowerPrompt = (originalUserPrompt || "").toLowerCase()
  const lowerText = text.toLowerCase()

  if (
    lowerText.includes("طوارئ") ||
    lowerText.includes("عاجل") ||
    lowerText.includes("اسعاف") ||
    lowerPrompt.includes("طوارئ") ||
    lowerPrompt.includes("urgent")
  ) {
    return "Opening Urgent Service flow immediately..."
  }

  if (
    lowerText.includes("جليس") ||
    lowerText.includes("مرافق") ||
    lowerText.includes("حجز") ||
    lowerPrompt.includes("جليس") ||
    lowerPrompt.includes("احجز")
  ) {
    return "Opening companion booking flow now..."
  }

  if (
    lowerText.includes("موقع") ||
    lowerText.includes("جي بي اس") ||
    lowerPrompt.includes("موقع")
  ) {
    return "Acquiring live GPS telemetry..."
  }

  if (
    lowerText.includes("خارج") ||
    lowerText.includes("حصري") ||
    lowerText.includes("نطاق")
  ) {
    return "I am right here with you! While my core passion is eldercare and helping families across Wanes, I am always glad to chat. How can I assist you or your family today?"
  }

  const englishOnly = text.replace(/[\u0600-\u06FF]/g, "").replace(/\s+/g, " ").trim()
  if (englishOnly.length >= 15) {
    return englishOnly
  }

  return "I understand your request. I am here to help you navigate Wanes Care services, book verified companions, and manage platform safety in English."
}

export function parseLLMJsonOutput(raw: string): {
  message: string
  action: NOVACompanionAction | null
} {
  const cleanRaw = raw.trim()
  if (!cleanRaw) {
    return { message: "No response generated by LLM.", action: null }
  }

  try {
    const parsed = JSON.parse(cleanRaw)
    if (parsed && typeof parsed === "object") {
      const message =
        typeof parsed.message === "string"
          ? parsed.message
          : typeof parsed.text === "string"
          ? parsed.text
          : cleanRaw
      return {
        message,
        action: parsed.action || null,
      }
    }
  } catch {}

  const fenceMatch = cleanRaw.match(/```(?:json)?\s*([\s\S]*?)\s*```/i)
  if (fenceMatch) {
    try {
      const parsed = JSON.parse(fenceMatch[1].trim())
      if (parsed && typeof parsed === "object") {
        return {
          message: parsed.message || parsed.text || cleanRaw.replace(fenceMatch[0], "").trim(),
          action: parsed.action || null,
        }
      }
    } catch {}
  }

  const firstBrace = cleanRaw.indexOf("{")
  const lastBrace = cleanRaw.lastIndexOf("}")
  if (firstBrace !== -1 && lastBrace > firstBrace) {
    try {
      const potentialJson = cleanRaw.slice(firstBrace, lastBrace + 1)
      const parsed = JSON.parse(potentialJson)
      if (parsed && typeof parsed === "object" && (parsed.message || parsed.action)) {
        return {
          message: parsed.message || parsed.text || cleanRaw,
          action: parsed.action || null,
        }
      }
    } catch {}
  }

  return {
    message: cleanRaw,
    action: null,
  }
}

